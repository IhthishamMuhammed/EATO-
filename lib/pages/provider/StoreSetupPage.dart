  Widget _buildEnhancedTextField({
    required TextEditingController controller,
    required String labelText,
    required String hintText,
    required IconData prefixIcon,
    TextInputType? keyboardType,
    int maxLines = 1,
    bool isRequired = false,
    String? Function(String?)? validator,
  }) {
    return Container(
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(16),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withOpacity(0.05),
            blurRadius: 10,
            offset: Offset(0, 2),
          ),
        ],
      ),
      child: TextFormField(
        controller: controller,
        keyboardType: keyboardType,
        maxLines: maxLines,
        validator: validator,
        decoration: InputDecoration(
          labelText: labelText + (isRequired ? ' *' : ''),
          hintText: hintText,
          prefixIcon: Container(
            margin: EdgeInsets.only(right: 12),
            decoration: BoxDecoration(
              color: EatoTheme.primaryColor.withOpacity(0.1),
              borderRadius: BorderRadius.only(
                topLeft: Radius.circular(16),
                bottomLeft: Radius.circular(16),
              ),
            ),
            child: Icon(prefixIcon, color: EatoTheme.primaryColor),
          ),
          labelStyle: TextStyle(
            color: EatoTheme.primaryColor,
            fontWeight: FontWeight.w500,
          ),
          hintStyle: TextStyle(color: Colors.grey[400]),
          border: OutlineInputBorder(
            borderRadius: BorderRadius.circular(16),
            borderSide: BorderSide.none,
          ),
          focusedBorder: OutlineInputBorder(
            borderRadius: BorderRadius.circular(16),
            borderSide: BorderSide(color: EatoTheme.primaryColor, width: 2),
          ),
          errorBorder: OutlineInputBorder(
            borderRadius: BorderRadius.circular(16),
            borderSide: BorderSide(color: Colors.red, width: 2),
          ),
          filled: true,
          fillColor: Colors.white,
          contentPadding: EdgeInsets.symmetric(horizontal: 20, vertical: 16),
        ),
      ),
    );
  }

  Widget _buildLocationPicker() {
    return GestureDetector(
      onTap: () async {
        try {
          final result = await Navigator.push<LocationData>(
            context,
            MaterialPageRoute(
              builder: (context) => LocationPickerPage(
                initialLocation:
                    _selectedLatitude != null && _selectedLongitude != null
                        ? GeoPoint(_selectedLatitude!, _selectedLongitude!)
                        : null,
                initialAddress: _storeLocationController.text,
              ),
            ),
          );

          if (result != null) {
            setState(() {
              _storeLocationController.text = result.formattedAddress;
              _selectedLatitude = result.geoPoint.latitude;
              _selectedLongitude = result.geoPoint.longitude;
            });
          }
        } catch (e) {
          _showSnackBar('Error selecting location: $e', EatoTheme.errorColor);
        }
      },
      child: Container(
        width: double.infinity,
        padding: EdgeInsets.all(20),
        decoration: BoxDecoration(
          color: Colors.white,
          borderRadius: BorderRadius.circular(16),
          border: Border.all(
            color: _storeLocationController.text.isNotEmpty
                ? EatoTheme.primaryColor.withOpacity(0.3)
                : Colors.grey.shade300,
