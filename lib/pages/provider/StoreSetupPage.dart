  Future<void> _pickStoreImage() async {
    try {
      final ImagePicker picker = ImagePicker();
      final XFile? image = await picker.pickImage(
        source: ImageSource.gallery,
        imageQuality: 80,
      );

      if (image != null) {
        setState(() {
          _pickedStoreImage = image;
        });

        if (kIsWeb) {
          final bytes = await image.readAsBytes();
          setState(() {
            _webStoreImageData = bytes;
          });
        }
      }
    } catch (e) {
      _showSnackBar('Error picking image: $e', EatoTheme.errorColor);
    }
  }

  Future<String?> _uploadStoreImage() async {
    if (_pickedStoreImage == null) return null;

    try {
      final fileName =
          'store_${widget.currentUser.id}_${DateTime.now().millisecondsSinceEpoch}';
      final ref =
          FirebaseStorage.instance.ref().child('store_images/$fileName');

      if (kIsWeb) {
        await ref.putData(_webStoreImageData!);
      } else {
        await ref.putFile(io.File(_pickedStoreImage!.path));
      }

      return await ref.getDownloadURL();
    } catch (e) {
      print('Error uploading store image: $e');
      return null;
    }
  }

  Future<void> _createStore() async {
    if (!_formKey.currentState!.validate()) return;

    setState(() {
      _isLoading = true;
    });

    try {
      // Upload image if selected
      String? storeImageUrl;
      if (_pickedStoreImage != null) {
        storeImageUrl = await _uploadStoreImage();
      }

      // Create the new store
      final Store newStore = Store(
        id: '', // Will be generated by Firestore
        name: _storeNameController.text.trim(),
        contact: _storeContactController.text.trim(),
        deliveryMode: _selectedDeliveryMode,
        imageUrl: storeImageUrl ?? '',
        foods: [], // Empty initially
        location: _storeLocationController.text.trim().isEmpty
            ? null
            : _storeLocationController.text.trim(),
        latitude: _selectedLatitude,
        longitude: _selectedLongitude,
        ownerUid: widget.currentUser.id,
        isActive: true,
        isAvailable: true,
        rating: null,
      );

      final storeProvider = Provider.of<StoreProvider>(context, listen: false);
      await storeProvider.createOrUpdateStore(newStore, widget.currentUser.id);

      // Ensure the store was created successfully
      await storeProvider.fetchUserStore(widget.currentUser);

      if (mounted) {
        _showSnackBar('Store created successfully!', EatoTheme.successColor);

        // Navigate to main provider navigation
        await Future.delayed(Duration(milliseconds: 1500));

        if (mounted) {
          Navigator.pushAndRemoveUntil(
            context,
            MaterialPageRoute(
              builder: (context) => ProviderMainNavigation(
                currentUser: widget.currentUser,
                initialIndex: 2, // Menu tab
              ),
            ),
            (route) => false,
          );
        }
      }
    } catch (e) {
      print('Error creating store: $e');
      if (mounted) {
        _showSnackBar('Failed to create store: $e', EatoTheme.errorColor);
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

  void _showSnackBar(String message, Color backgroundColor) {
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Row(
            children: [
              Icon(
                backgroundColor == EatoTheme.errorColor
                    ? Icons.error
                    : Icons.check_circle,
                color: Colors.white,
              ),
              SizedBox(width: 8),
              Expanded(child: Text(message)),
            ],
          ),
          backgroundColor: backgroundColor,
          behavior: SnackBarBehavior.floating,
          shape:
              RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
        ),
      );
    }
  }

